import { DiagnosticSeverity } from "vscode-languageserver";
import { EmptyFileSystem } from "langium";
import { expectIssue, expectNoIssues, validationHelper } from "langium/test";
import { describe, expect, test } from "vitest";
import { createExpressP11Services } from "../language/express-module.js";
import { ExpressP11Issues } from "../language/express-p11-validator.js";

const services = createExpressP11Services(EmptyFileSystem).ExpressP11;
const validate = validationHelper(services);
const code = ExpressP11Issues.ReferenceNameCase;

/**
 * XS-PUB-004 (docs/REQUIREMENTS-annotation-publication-checks.md): a reference is spelled as the declaration it
 * binds to, and a schema name in an interface clause follows the WG 12 convention (resource schemas lower case,
 * ARM and MIM schemas with an initial upper-case letter). EXPRESS reads names regardless of case; the spelling is
 * a WG 12 rule (RUL-26, RUL-36). The ISO 10303-2 build resolves names by exact spelling, so a supertype written
 * in another case than its declaration is linked to another schema's declaration of that spelling.
 */
describe("reference-name-case: a reference spelled unlike its declaration", () => {
  test("a type written in another case binds and is reported", async () => {
    const result = await validate(`
      SCHEMA s;
      TYPE unit_kind = STRING; END_TYPE;
      ENTITY e; u : Unit_kind; END_ENTITY;
      END_SCHEMA;
    `);
    expectIssue(result, {
      code,
      message: "Reference 'Unit_kind' is spelled differently from its declaration 'unit_kind'.",
      severity: DiagnosticSeverity.Warning,
      data: { expectedName: "unit_kind" },
    });
  });

  test("a reference spelled as declared is not reported", async () => {
    const result = await validate(`
      SCHEMA s;
      TYPE unit_kind = STRING; END_TYPE;
      ENTITY Base; END_ENTITY;
      ENTITY e SUBTYPE OF (Base); u : unit_kind; END_ENTITY;
      END_SCHEMA;
    `);
    expectNoIssues(result, { code });
  });

  test("short form: a supertype in another case, which does not bind, names the declaration", async () => {
    const result = await validate(`
      SCHEMA Kinematic_structure_arm;
      ENTITY Screw_pair; END_ENTITY;
      ENTITY Screw_pair_with_range SUBTYPE OF (screw_pair); END_ENTITY;
      END_SCHEMA;
    `);
    expectIssue(result, {
      code,
      message: "Reference 'screw_pair' is spelled differently from its declaration 'Screw_pair'.",
      severity: DiagnosticSeverity.Warning,
      data: { expectedName: "Screw_pair" },
    });
  });

  test("long form: not checked (generated by eengine, names unique regardless of case, WG11 N239)", async () => {
    const result = await validate(`
      SCHEMA s_mim_lf;
      ENTITY Value_with_unit; END_ENTITY;
      ENTITY measure SUBTYPE OF (value_with_unit); END_ENTITY;
      END_SCHEMA;
    `);
    expectNoIssues(result, { code });
  });

  test("an interfaced item in another case is reported; a renamed item is read under its new name", async () => {
    const result = await validate(`
      SCHEMA a;
      TYPE unit_kind = STRING; END_TYPE;
      TYPE label = STRING; END_TYPE;
      END_SCHEMA;
      SCHEMA b;
      USE FROM a (Unit_kind, label AS Kind);
      ENTITY e; k : Kind; END_ENTITY;
      END_SCHEMA;
    `);
    expectIssue(result, { code, data: { expectedName: "unit_kind" } });
    expect(result.diagnostics.filter((d) => d.code === code)).toHaveLength(1);
  });
});

describe("reference-name-case: schema names in interface clauses", () => {
  test("a resource schema name with an upper-case letter is reported", async () => {
    const result = await validate(`
      SCHEMA Product_data_quality_criteria_mim;
      USE FROM Product_data_quality_criteria_schema;
      END_SCHEMA;
    `);
    expectIssue(result, {
      code,
      message:
        "Schema name 'Product_data_quality_criteria_schema' should be 'product_data_quality_criteria_schema': resource schemas are lower case, ARM and MIM schemas start with an upper-case letter.",
      severity: DiagnosticSeverity.Warning,
      data: { expectedName: "product_data_quality_criteria_schema" },
    });
  });

  test("an ARM or MIM schema name without an initial upper-case letter is reported", async () => {
    const result = await validate(`
      SCHEMA Curve_swept_solid_mim;
      USE FROM elemental_geometric_shape_mim;
      REFERENCE FROM kinematic_structure_arm;
      END_SCHEMA;
    `);
    expectIssue(result, { code, data: { expectedName: "Elemental_geometric_shape_mim" } });
    expectIssue(result, { code, data: { expectedName: "Kinematic_structure_arm" } });
  });

  test("conventional interface schema names are not reported", async () => {
    const result = await validate(`
      SCHEMA Curve_swept_solid_mim;
      USE FROM Elemental_geometric_shape_mim;
      REFERENCE FROM support_resource_schema;
      USE FROM Kinematic_structure_arm_lf;
      END_SCHEMA;
    `);
    expectNoIssues(result, { code });
  });

  test("a schema in the workspace spelled in another case is reported once, naming its declaration", async () => {
    const result = await validate(`
      SCHEMA support_resource_schema;
      TYPE label = STRING; END_TYPE;
      END_SCHEMA;
      SCHEMA b;
      REFERENCE FROM Support_resource_schema (label);
      END_SCHEMA;
    `);
    const found = result.diagnostics.filter((d) => d.code === code);
    expect(found.map((d) => d.message)).toEqual([
      "Reference 'Support_resource_schema' is spelled differently from its declaration 'support_resource_schema'.",
    ]);
  });
});

describe("reference-name-case: quick fix", () => {
  test("respells the reference as declared", async () => {
    const input = `
      SCHEMA s;
      TYPE unit_kind = STRING; END_TYPE;
      ENTITY e; u : Unit_kind; END_ENTITY;
      END_SCHEMA;
    `;
    const result = await validate(input);
    const diagnostic = result.diagnostics.find((d) => d.code === code);
    expect(diagnostic).toBeDefined();
    const actions = await services.lsp.CodeActionProvider?.getCodeActions(result.document, {
      textDocument: { uri: result.document.uri.toString() },
      range: diagnostic!.range,
      context: { diagnostics: [diagnostic!] },
    });
    const action = actions?.[0];
    const edit = action && "edit" in action ? action.edit?.changes?.[result.document.uri.toString()]?.[0] : undefined;
    expect(edit?.newText).toBe("unit_kind");
    const start = result.document.textDocument.offsetAt(edit!.range.start);
    const end = result.document.textDocument.offsetAt(edit!.range.end);
    expect(input.slice(start, end)).toBe("Unit_kind");
  });
});
